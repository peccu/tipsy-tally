const dict: Record<Lang, Record<Key, string>> = { ja, en };

export function resolveLang(setting: Settings['lang']): Lang {
  if (setting !== 'auto') return setting;
  return (navigator.languages?.[0] ?? navigator.language ?? 'en').toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

export type T = (key: Key, params?: Record<string, string | number>) => string;

export interface I18n {
  lang: Lang;
  t: T;
  /** Format an amount (stored as grams) in the user's unit. */
  amt: (grams: number, digits?: number) => string;
  amtNum: (grams: number, digits?: number) => string;
  unit: string;
  name: (d: { preset?: string; name?: string }) => string;
}

export function useI18n(): I18n {
  const { settings } = useData();
  const lang = resolveLang(settings.lang);
  const table = dict[lang];
  const t: T = (key, params) =>
    (table[key] ?? key).replace(/\{(\w+)\}/g, (_, p) => String(params?.[p] ?? ''));
  const ml = settings.unit === 'ml';
  const unit = ml ? 'ml' : 'g';
  const amtNum = (g: number, digits = 1) => {
    const v = ml ? g / 0.8 : g;
    return v.toLocaleString(lang, { minimumFractionDigits: digits, maximumFractionDigits: digits });
  };
  return {
    lang,
    t,
    unit,
    amtNum,
    amt: (g, digits) => `${amtNum(g, digits)}${unit}`,
    name: (d) => d.name || (d.preset ? t(`preset.${d.preset}` as Key) : '—'),
  };
}
